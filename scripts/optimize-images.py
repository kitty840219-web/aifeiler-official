"""Regenerate WebP assets and article previews. Requires Pillow (python -m pip install Pillow)."""
from pathlib import Path
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / 'public'
MANIFEST = json.loads((ROOT / 'docs/image-optimization-manifest.json').read_text())

for record in MANIFEST['converted']:
    old = '/images/' + record['source']
    target = PUBLIC / MANIFEST['pathChanges'][old].lstrip('/')
    source = ROOT / 'assets/source-images' / record['source']
    target.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(source) as image:
        image.save(target, 'WEBP', quality=88, method=6, exact=True)

thumbnails = {}
for source in sorted((PUBLIC / 'images/articles').glob('*.webp')):
    target = PUBLIC / 'images/articles/thumbnails' / source.name
    target.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(source) as image:
        image.thumbnail((640, 640), Image.Resampling.LANCZOS)
        image.save(target, 'WEBP', quality=80, method=6)
    thumbnails['/images/articles/' + source.name] = '/images/articles/thumbnails/' + source.name
(ROOT / 'lib/data/imageThumbnails.ts').write_text(
    '// Generated by scripts/optimize-images.py. Full-size images remain available in article dialogs.\n'
    + 'export const ARTICLE_THUMBNAILS: Record<string, string> = '
    + json.dumps(thumbnails, ensure_ascii=False, indent=2) + ';\n'
)
